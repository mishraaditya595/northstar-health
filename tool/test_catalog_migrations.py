"""Checks on the generated catalogue publish migrations.

Each `*_catalog_release_<n>.sql` must be exactly what scripts/catalog_build.py
would write for its snapshot, must agree with its entry in
catalog/releases.lock.json, and must still pass the validator against the
releases locked before it. Every lock entry needs exactly one migration.
"""
import hashlib
import json
import re
import shutil
import tempfile
import unittest
from pathlib import Path

from scripts.catalog_build import canonical_bytes, load_lock, lock_entry
from scripts.catalog_validate import validate_snapshot

ROOT = Path(__file__).resolve().parent.parent
TAG = "$catalog$"
NAME = re.compile(r"^(\d{14})_catalog_release_(\d+)\.sql$")
LAYOUT = re.compile(
    r"\A-- Catalogue release (?P<n>\d+)\n"
    r"-- sha256: (?P<head_sha>[0-9a-f]{64})\n"
    r"-- Generated by scripts/catalog_build\.py; do not edit\.\n"
    r"select northstar_private\.publish_catalog_release\(\n"
    r"  (?P<arg_release>\d+),\n"
    r"  (?P<schema>\d+),\n"
    r"  (?P<min_schema>\d+),\n"
    r"  \$catalog\$(?P<body>.*)\$catalog\$::jsonb,\n"
    r"  '(?P<arg_sha>[0-9a-f]{64})',\n"
    r"  (?P<size>\d+),\n"
    r"  '(?P<published>[^']+)'::timestamptz\n"
    r"\);\n\Z",
    re.DOTALL,
)


def check_migrations(migrations, lock):
    """Return a list of problems; empty means every release migration is sound."""
    errors = []
    found = {}
    for path in sorted(Path(migrations).glob("*_catalog_release_*.sql")):
        match = NAME.match(path.name)
        if not match:
            errors.append(f"{path.name}: unexpected file name")
            continue
        found.setdefault(int(match.group(2)), []).append(path)

    locked = {entry["release"]: entry for entry in lock["releases"]}
    for release in sorted(locked):
        count = len(found.get(release, []))
        if count != 1:
            errors.append(f"release {release}: {count} migrations, expected 1")
    for release in sorted(set(found) - set(locked)):
        errors.append(f"release {release}: migration without a lock entry")

    for release, paths in sorted(found.items()):
        for path in paths:
            errors.extend(_check_one(path, release, locked.get(release), lock))
    return errors


def _check_one(path, release, entry, lock):
    name = path.name
    parts = LAYOUT.match(path.read_text(encoding="utf-8"))
    if not parts:
        return [f"{name}: does not match the generated layout"]
    body = parts["body"]
    errors = []
    try:
        snapshot = json.loads(body)
    except ValueError as exc:
        return [f"{name}: body is not JSON ({exc})"]
    canonical = canonical_bytes(snapshot)
    if body.encode("utf-8") != canonical:
        errors.append(f"{name}: body is not byte-identical to its canonical form")
    sha = hashlib.sha256(canonical).hexdigest()
    size = len(canonical)
    for label, value, want in [
        ("header sha256", parts["head_sha"], sha),
        ("publish sha256", parts["arg_sha"], sha),
        ("size_bytes", int(parts["size"]), size),
        ("header release", int(parts["n"]), release),
        ("publish release", int(parts["arg_release"]), release),
        ("body release", snapshot.get("release"), release),
        ("schemaVersion", int(parts["schema"]), snapshot.get("schemaVersion")),
        (
            "minAppCatalogSchema",
            int(parts["min_schema"]),
            snapshot.get("minAppCatalogSchema"),
        ),
        ("publishedAt", parts["published"], snapshot.get("publishedAt")),
    ]:
        if value != want:
            errors.append(f"{name}: {label} is {value!r}, expected {want!r}")
    if entry is not None and entry != lock_entry(snapshot, sha):
        errors.append(f"{name}: differs from its entry in releases.lock.json")
    before = {"releases": [r for r in lock["releases"] if r["release"] < release]}
    for problem in validate_snapshot(snapshot, before):
        errors.append(f"{name}: validator: {problem}")
    return errors


class CatalogMigrationsTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.lock = load_lock(ROOT / "catalog/releases.lock.json")

    def copy_migrations(self):
        tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, tmp, True)
        for path in (ROOT / "supabase/migrations").glob("*_catalog_release_*.sql"):
            shutil.copy(path, tmp / path.name)
        return tmp

    def mutate(self, tmp, release, old, new, count=1):
        path = next(tmp.glob(f"*_catalog_release_{release}.sql"))
        text = path.read_text(encoding="utf-8")
        self.assertIn(old, text)
        path.write_text(text.replace(old, new, count), encoding="utf-8")

    def test_repository_migrations_are_sound(self):
        self.assertEqual(
            check_migrations(ROOT / "supabase/migrations", self.lock), []
        )

    def test_there_is_a_migration_per_lock_entry(self):
        self.assertGreaterEqual(len(self.lock["releases"]), 4)

    def test_tampered_body_is_caught(self):
        tmp = self.copy_migrations()
        self.mutate(tmp, 4, '"name":"Ab crunch machine"', '"name":"Ab  crunch machine"')
        errors = check_migrations(tmp, self.lock)
        self.assertTrue(any("sha256" in e for e in errors), errors)

    def test_non_canonical_body_is_caught(self):
        tmp = self.copy_migrations()
        self.mutate(tmp, 3, '{"exercises":', '{ "exercises":')
        errors = check_migrations(tmp, self.lock)
        self.assertTrue(any("byte-identical" in e for e in errors), errors)

    def test_header_hash_mismatch_is_caught(self):
        tmp = self.copy_migrations()
        path = next(tmp.glob("*_catalog_release_2.sql"))
        text = path.read_text(encoding="utf-8")
        sha = re.search(r"-- sha256: ([0-9a-f]{64})", text).group(1)
        path.write_text(
            text.replace(f"-- sha256: {sha}", "-- sha256: " + "0" * 64, 1),
            encoding="utf-8",
        )
        errors = check_migrations(tmp, self.lock)
        self.assertTrue(any("header sha256" in e for e in errors), errors)

    def test_wrong_size_argument_is_caught(self):
        tmp = self.copy_migrations()
        path = next(tmp.glob("*_catalog_release_4.sql"))
        text = path.read_text(encoding="utf-8")
        size = LAYOUT.match(text)["size"]
        path.write_text(
            text.replace(f"  {size},\n  '2026", f"  {int(size) + 1},\n  '2026"),
            encoding="utf-8",
        )
        errors = check_migrations(tmp, self.lock)
        self.assertTrue(any("size_bytes" in e for e in errors), errors)

    def test_lock_that_disagrees_is_caught(self):
        tmp = self.copy_migrations()
        lock = json.loads(json.dumps(self.lock))
        lock["releases"][2]["sha256"] = "1" * 64
        errors = check_migrations(tmp, lock)
        self.assertTrue(any("releases.lock.json" in e for e in errors), errors)

    def test_missing_and_extra_migrations_are_caught(self):
        tmp = self.copy_migrations()
        next(tmp.glob("*_catalog_release_3.sql")).unlink()
        errors = check_migrations(tmp, self.lock)
        self.assertTrue(any("release 3: 0 migrations" in e for e in errors), errors)

        tmp = self.copy_migrations()
        src = next(tmp.glob("*_catalog_release_2.sql"))
        shutil.copy(src, tmp / "20261126031000_catalog_release_2.sql")
        errors = check_migrations(tmp, self.lock)
        self.assertTrue(any("release 2: 2 migrations" in e for e in errors), errors)

        tmp = self.copy_migrations()
        lock = {"releases": self.lock["releases"][:3]}
        errors = check_migrations(tmp, lock)
        self.assertTrue(any("without a lock entry" in e for e in errors), errors)

    def test_validator_rerun_catches_a_removed_exercise(self):
        tmp = self.copy_migrations()
        lock = json.loads(json.dumps(self.lock))
        # Lock claims release 1 had an exercise that release 2+ no longer has.
        lock["releases"][0]["exercises"]["builtin.v1.gone"] = "reps_load"
        errors = check_migrations(tmp, lock)
        self.assertTrue(any("validator" in e for e in errors), errors)


if __name__ == "__main__":
    unittest.main()
